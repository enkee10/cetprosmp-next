const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const tree = { exports: {} };
new Function('exports', ts.transpileModule(fs.readFileSync('functions/src/modules/academico/contentTree.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(tree.exports);
const { moveContentBranch } = tree.exports;

module.exports = async function checkContentTree({ page, load, card, resolve, reject }) {
  await load();
  const indicator = card('indicadorCapacidad', 40);
  const rootAdd = indicator.getByRole('button', { name: 'Agregar contenido', exact: true });
  assert.equal(await indicator.getByRole('textbox').count(), 0, 'The content input is initially hidden');
  const headingBox = await indicator.getByText('Contenidos', { exact: true }).boundingBox();
  const rootAddBox = await rootAdd.boundingBox();
  assert(Math.abs(headingBox.y - rootAddBox.y) < 8, 'The root plus shares the label line');
  await rootAdd.click();
  assert.equal(await indicator.getByRole('button', { name: 'Subcontenido', exact: true }).count(), 0, 'The heading plus creates only root contents');
  await indicator.getByRole('textbox').fill('Descartar este borrador');
  await indicator.getByRole('button', { name: 'Cancelar cambios', exact: true }).click();
  assert.equal(await indicator.getByRole('textbox').count(), 0);
  assert.equal(await page.evaluate(() => window.requests.length), 0, 'Cancel must close the new content editor without saving');
  await rootAdd.click();
  await indicator.getByRole('textbox', { name: 'Nuevos contenidos (uno por línea)' }).fill('Seguridad');
  await indicator.getByRole('textbox').press('Enter');
  assert.equal(await indicator.getByRole('textbox').inputValue(), 'Seguridad\n', 'Enter inserts a newline in the new content editor');
  assert.equal(await page.evaluate(() => window.requests.length), 0, 'Enter must not save new contents');
  await indicator.getByRole('textbox').pressSequentially('Herramientas');
  await indicator.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await page.waitForFunction(() => window.requests.length === 1);
  assert.equal(await page.evaluate(() => window.requests.at(-1).input.contenidoPadreId), null);
  await indicator.getByText('Contenidos', { exact: true }).click();
  assert.equal(await page.evaluate(() => window.requests.length), 1, 'Save followed by blur must not double-save');
  let contents = [
    { id: 1, orden: 1, texto: 'Seguridad', contenidoPadreId: null },
    { id: 2, orden: 2, texto: 'Herramientas', contenidoPadreId: null },
  ];
  await resolve({ items: contents });
  const content = id => indicator.locator(`[data-content-id="${id}"]`);
  const row = id => content(id).locator(':scope > .MuiStack-root');
  await content(1).waitFor();
  assert.equal(await indicator.getByRole('textbox').count(), 0, 'Successful creation closes the transient input');
  const textBox = await row(1).locator('span[title="Doble clic para editar"]').boundingBox();
  const plusBox = await row(1).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).boundingBox();
  const removeBox = await row(1).getByRole('button', { name: 'Quitar contenido', exact: true }).boundingBox();
  assert(Math.abs(removeBox.x - plusBox.x - plusBox.width - 2) < 1, 'The child plus aligns to the right immediately before the delete button');
  assert(Math.abs(plusBox.y - textBox.y) < 8, 'The child plus stays on the name line');
  await row(1).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).click();
  await indicator.getByRole('textbox', { name: 'Nuevos contenidos (uno por línea)' }).fill('Protección\nPrevención');
  const childAction = indicator.getByRole('button', { name: 'Subcontenido', exact: true });
  assert.equal(await childAction.locator('[data-testid="SubdirectoryArrowRightIcon"]').count(), 1);
  assert((await childAction.boundingBox()).x < (await indicator.getByRole('button', { name: 'Guardar cambios', exact: true }).boundingBox()).x, 'Subcontenido stays to the left of the green check');
  await childAction.click();
  await indicator.getByText('Contenidos', { exact: true }).click();
  await page.waitForFunction(() => window.requests.length === 2);
  assert.equal(await page.evaluate(() => window.requests.at(-1).input.contenidoPadreId), 1);
  assert.equal(await page.evaluate(() => window.requests.at(-1).input.despuesDeId), undefined, 'Saving as a child must not also insert a sibling');
  contents.push({ id: 3, orden: 3, texto: 'Protección', contenidoPadreId: 1 }, { id: 4, orden: 4, texto: 'Prevención', contenidoPadreId: 1 });
  await resolve({ items: contents });
  await content(3).waitFor();
  assert.equal(await indicator.locator('[data-content-children="1"]').evaluate(element => getComputedStyle(element).marginLeft), '8px');
  assert.equal((await content(3).boundingBox()).x - (await content(1).boundingBox()).x, 8);
  await row(3).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).click();
  const nestedEditor = indicator.locator('[data-content-editor-after="3"]');
  assert.equal(await nestedEditor.getAttribute('data-content-editor-parent'), '1');
  assert.equal((await nestedEditor.boundingBox()).x, (await content(3).boundingBox()).x, 'The default editor uses the clicked row’s level');
  await indicator.getByRole('textbox').fill('Hermano intermedio');
  await indicator.getByText('Contenidos', { exact: true }).click();
  await page.waitForFunction(() => window.requests.length === 3);
  assert.deepEqual(await page.evaluate(() => ({ parent: window.requests.at(-1).input.contenidoPadreId, after: window.requests.at(-1).input.despuesDeId })), { parent: 1, after: 3 });
  contents = contents.map(item => ({ ...item, orden: item.orden > 3 ? item.orden + 1 : item.orden }));
  contents.push({ id: 7, orden: 4, texto: 'Hermano intermedio', contenidoPadreId: 1 });
  await resolve({ items: contents });
  await content(7).waitFor();
  assert.deepEqual(await indicator.locator('[data-content-children="1"] > ul > li').evaluateAll(elements => elements.map(element => Number(element.dataset.contentId))), [3, 7, 4]);
  await row(7).getByRole('button', { name: 'Quitar contenido', exact: true }).click();
  await page.waitForFunction(() => window.requests.length === 4);
  contents = contents.filter(item => item.id !== 7);
  await resolve({ items: contents });
  await content(7).waitFor({ state: 'detached' });
  for (const [parentId, id, texto] of [[3, 5, 'Guantes'], [5, 6, 'Inspección']]) {
    const count = await page.evaluate(() => window.requests.length);
    await row(parentId).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).click();
    await indicator.getByRole('textbox').fill(texto);
    await indicator.getByRole('button', { name: 'Subcontenido', exact: true }).click();
    await page.waitForFunction(count => window.requests.length === count + 1, count);
    contents.push({ id, orden: Math.max(...contents.map(item => item.orden)) + 1, texto, contenidoPadreId: parentId });
    await resolve({ items: contents });
    await content(id).waitFor();
    assert.equal((await content(id).boundingBox()).x - (await content(parentId).boundingBox()).x, 8, 'Every nested level adds exactly 8 px');
  }
  await row(3).locator('span[title="Doble clic para editar"]').dblclick();
  const editCount = () => page.evaluate(() => window.calls.filter(call => call.name === 'updateEstructuraAcademicaCell').length);
  let updates = await editCount();
  await row(3).getByRole('textbox').fill('Equipos de protección');
  await row(3).getByRole('textbox').press('Enter');
  assert.equal(await row(3).getByRole('textbox').inputValue(), 'Equipos de protección\n');
  assert.equal(await editCount(), updates, 'Enter must not save an existing content');
  await row(3).getByRole('textbox').pressSequentially('Seguridad');
  await row(3).getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await row(3).getByRole('textbox').waitFor({ state: 'detached' });
  assert.equal(await row(3).locator('span[title="Doble clic para editar"]').textContent(), 'Equipos de protección\nSeguridad', 'Save preserves line breaks within an existing content');
  assert.equal(await editCount(), updates + 1);
  await row(3).locator('span[title="Doble clic para editar"]').dblclick();
  await row(3).getByRole('textbox').fill('Descartar esta edición');
  await row(3).getByRole('button', { name: 'Cancelar cambios', exact: true }).click();
  assert.equal(await editCount(), updates + 1, 'Cancel must not save or delete an existing content');
  assert.equal(await row(3).locator('span[title="Doble clic para editar"]').textContent(), 'Equipos de protección\nSeguridad');
  await row(3).locator('span[title="Doble clic para editar"]').dblclick();
  await row(3).getByRole('textbox').fill('Equipos de protección\nPrevención');
  await indicator.getByText('Contenidos', { exact: true }).click();
  await row(3).getByRole('textbox').waitFor({ state: 'detached' });
  assert.equal(await row(3).locator('span[title="Doble clic para editar"]').textContent(), 'Equipos de protección\nPrevención', 'Blur also saves existing content');
  contents = contents.map(item => item.id === 3 ? { ...item, texto: 'Equipos de protección\nPrevención' } : item);
  const drag = async (sourceId, targetId, position = 'before') => {
    const transfer = await page.evaluateHandle(() => new DataTransfer());
    await row(sourceId).locator('[draggable="true"]').dispatchEvent('dragstart', { dataTransfer: transfer });
    const target = targetId == null ? indicator.locator('[data-content-root-drop]') : row(targetId);
    await target.waitFor();
    const rect = await target.boundingBox();
    const clientY = position === 'before' ? rect.y + 1 : position === 'after' ? rect.y + rect.height - 1 : rect.y + rect.height / 2;
    await target.dispatchEvent('dragover', { dataTransfer: transfer, clientY });
    await target.dispatchEvent('drop', { dataTransfer: transfer, clientY });
    await row(sourceId).locator('[draggable]').dispatchEvent('dragend', { dataTransfer: transfer });
  };
  const move = async (itemId, targetId, position) => {
    const count = await page.evaluate(() => window.requests.length);
    await drag(itemId, targetId, position);
    await page.waitForFunction(count => window.requests.length === count + 1, count);
    const input = await page.evaluate(() => window.requests.at(-1).input);
    assert.equal(input.action, 'move');
    assert.deepEqual({ itemId: input.itemId, targetId: input.targetId, position: input.position }, { itemId, targetId, position });
    const ordered = moveContentBranch(contents, input);
    contents = ordered.map(position => ({ ...contents.find(item => item.id === position.id), ...position }));
    await resolve({ items: contents });
    await indicator.getByRole('progressbar', { name: 'Moviendo contenidos' }).waitFor({ state: 'detached' });
  };
  await move(4, 3, 'before');
  assert.deepEqual(contents.map(item => item.id), [1, 4, 3, 5, 6, 2], 'Reordering preserves complete nested branches');
  await page.waitForFunction(() => document.querySelector('[data-content-children="1"] > ul > li')?.getAttribute('data-content-id') === '4');
  let requestCount = await page.evaluate(() => window.requests.length);
  await drag(1, 5, 'inside');
  await drag(1, 1, 'inside');
  assert.equal(await page.evaluate(() => window.requests.length), requestCount, 'Self and descendant drops cannot create cycles');
  await move(1, 2, 'inside');
  await indicator.locator('[data-content-children="2"] > ul > [data-content-id="1"]').waitFor();
  assert.equal(await content(1).locator('[data-content-id]').count(), 4, 'Nesting a root preserves its full branch');
  await move(3, 2, 'inside');
  await indicator.locator('[data-content-children="2"] > ul > [data-content-id="3"]').waitFor();
  assert.equal(contents.find(item => item.id === 5).contenidoPadreId, 3);
  await move(3, null, 'inside');
  await indicator.locator('[aria-label="Lista de contenidos"] > [data-content-id="3"]').waitFor();
  assert.equal(await content(3).locator('[data-content-id]').count(), 2, 'Promoting a child preserves its descendants');
  await move(3, 1, 'inside');
  await move(1, 2, 'before');
  await move(4, 5, 'before');
  assert.equal(contents.find(item => item.id === 4).contenidoPadreId, 3, 'Dropping above another parent’s child changes the parent');
  await move(4, 1, 'inside');
  requestCount = await page.evaluate(() => window.requests.length);
  await drag(4, 2, 'inside');
  await page.waitForFunction(count => window.requests.length === count + 1, requestCount);
  await reject();
  await indicator.getByRole('progressbar', { name: 'Moviendo contenidos' }).waitFor({ state: 'detached' });
  await indicator.locator('[data-content-children="1"] > ul > [data-content-id="4"]').waitFor();
  requestCount = await page.evaluate(() => window.requests.length);
  await page.evaluate(() => { window.cancelDelete = true; });
  await row(1).getByRole('button', { name: 'Quitar contenido', exact: true }).click();
  assert.equal(await page.evaluate(() => window.requests.length), requestCount);
  assert((await page.evaluate(() => window.confirmations.at(-1).message)).includes('4 subcontenidos'));
  await page.evaluate(() => { window.cancelDelete = false; });
  await row(1).getByRole('button', { name: 'Quitar contenido', exact: true }).click();
  await page.waitForFunction(count => window.requests.length === count + 1, requestCount);
  assert.equal(await page.evaluate(() => window.requests.at(-1).input.includeDescendants), true);
  await row(1).locator('[role="progressbar"]').waitFor();
  contents = contents.filter(item => item.id === 2);
  await resolve({ items: contents });
  await content(1).waitFor({ state: 'detached' });
  await content(2).waitFor();
  assert.equal(await indicator.locator('[data-content-id]').count(), 1);
  await rootAdd.click();
  await indicator.getByRole('textbox').fill('Conservar borrador');
  await indicator.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await page.waitForFunction(count => window.requests.length === count + 2, requestCount);
  await reject();
  await indicator.getByRole('alert').filter({ hasText: 'Falló la solicitud' }).waitFor();
  assert.equal(await indicator.getByRole('textbox').inputValue(), 'Conservar borrador', 'A failed save preserves the draft');
  await indicator.getByRole('textbox').press('Escape');
  assert.equal(await indicator.getByRole('textbox').count(), 0);
  await row(2).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).click();
  await indicator.getByRole('textbox').fill('Borrador del hijo');
  requestCount = await page.evaluate(() => window.requests.length);
  await row(2).getByRole('button', { name: 'Quitar contenido', exact: true }).click();
  await page.waitForFunction(count => window.requests.length === count + 1, requestCount);
  await reject();
  await row(2).locator('[role="progressbar"]').waitFor({ state: 'detached' });
  assert.equal(await indicator.getByRole('textbox').inputValue(), 'Borrador del hijo', 'A failed parent deletion also preserves its unsaved child draft');
  await indicator.getByRole('textbox').press('Escape');
  await row(2).getByRole('button', { name: 'Agregar contenido debajo', exact: true }).click();
  await indicator.getByRole('textbox').fill('Hermano raíz');
  requestCount = await page.evaluate(() => window.requests.length);
  await indicator.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
  await page.waitForFunction(count => window.requests.length === count + 1, requestCount);
  assert.deepEqual(await page.evaluate(() => ({ parent: window.requests.at(-1).input.contenidoPadreId, after: window.requests.at(-1).input.despuesDeId })), { parent: null, after: 2 });
  contents.push({ id: 8, orden: Math.max(...contents.map(item => item.orden)) + 1, texto: 'Hermano raíz', contenidoPadreId: null });
  await resolve({ items: contents });
  await content(8).waitFor();
  assert.deepEqual(await indicator.locator('[aria-label="Lista de contenidos"] > li').evaluateAll(elements => elements.map(element => Number(element.dataset.contentId))), [2, 8]);
  console.log('Correcto en navegador: + crea hermanos, botón Subcontenido crea hijos sin doble guardado, Enter multilínea, cancelar, guardado al salir, arrastre entre niveles y recuperación tras fallos.');
};
