const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const moduleModel = {exports:{}};
const code = ts.transpileModule(fs.readFileSync('functions/src/modules/parte-diario/commitmentModel.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
new Function('exports',code)(moduleModel.exports);
const {normalizeCompromisos,followUpCompromiso,readCompromisos}=moduleModel.exports;
const created='2026-10-16T15:00:00Z',completed='2026-10-16T16:00:00Z';
const observations=['Primera observación','Segunda observación'];
let commitments=normalizeCompromisos([{id:null,observacionIndex:1,texto:' Entregar material ',cumplidoEn:completed,cumplidoPor:'forged'}],observations,[],'coord-a',created,()=> 'id-1');
assert.equal(commitments[0].creadoPor,'coord-a');assert.equal(commitments[0].creadoEn,created);
assert.equal(commitments[0].cumplidoEn,null);assert.equal(commitments[0].texto,'Entregar material');
assert.throws(()=>followUpCompromiso(commitments,'id-1','comentar','Antes de cumplir','coord-b',completed));
const before=commitments;
commitments=followUpCompromiso(commitments,'id-1','cumplir',undefined,'coord-b',completed);
assert.equal(before[0].cumplidoEn,null);assert.equal(commitments[0].cumplidoPor,'coord-b');
assert.equal(commitments[0].cumplidoEn,completed);assert.equal(commitments[0].comentario,null);
assert.equal(followUpCompromiso(commitments,'id-1','cumplir',undefined,'coord-c',created),commitments);
commitments=followUpCompromiso(commitments,'id-1','comentar',' Verificado ','coord-c',created);
assert.equal(commitments[0].comentario,'Verificado');assert.equal(commitments[0].comentadoPor,'coord-c');
assert.equal(followUpCompromiso(commitments,'id-1','comentar','Verificado','coord-d',completed),commitments);
assert.throws(()=>followUpCompromiso(commitments,'id-1','comentar','Otro comentario','coord-c',completed));
const moved=normalizeCompromisos([{...commitments[0],observacionIndex:0,cumplidoPor:'forged'}],observations.slice(1),commitments,'coord-d',completed,()=> 'new');
assert.equal(moved[0].observacionIndex,0);assert.equal(moved[0].cumplidoPor,'coord-b');assert.equal(moved[0].comentadoPor,'coord-c');
assert.throws(()=>normalizeCompromisos([{...commitments[0],texto:'Cambio'}],observations,commitments,'a',created,()=> 'new'));
assert.throws(()=>normalizeCompromisos([{...commitments[0],id:'foreign'}],observations,commitments,'a',created,()=> 'new'));
assert.throws(()=>normalizeCompromisos([commitments[0],commitments[0]],observations,commitments,'a',created,()=> 'new'));
assert.deepEqual(normalizeCompromisos([],observations,commitments,'a',created,()=> 'new'),[]);
assert.deepEqual(readCompromisos(null),[]);
console.log('Compromisos: auditoría protegida, índices, cumplimiento sin comentario, comentario único, reintentos y texto cumplido: correctos.');
