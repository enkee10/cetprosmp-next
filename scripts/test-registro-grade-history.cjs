const assert = require('node:assert/strict');
const { buildSync } = require('esbuild');
const compiled = buildSync({ entryPoints: ['src/lib/registroGradeHistory.ts'], bundle: true, write: false, platform: 'node', format: 'cjs' });
const loaded = { exports: {} };
new Function('module', 'exports', compiled.outputFiles[0].text)(loaded, loaded.exports);
const { RegistroGradeHistory } = loaded.exports;
const note = value => ({ kind: 'nota', matriculaId: 1, indicadorCapacidadId: 10, value });
const efsrt = value => ({ kind: 'efsrt', moduloEstudianteId: 20, value });
const edit = (before, after) => ({ before: note(before), after: note(after) });
const history = new RegistroGradeHistory();
const undo = () => history.undo()?.changes ?? [];
const redo = () => history.redo()?.changes ?? [];

assert.deepEqual(undo(), []);
assert.deepEqual(redo(), []);
history.record([edit(14, null)], 'cell');
history.record([edit(null, 1)], 'cell');
history.record([edit(1, 18)], 'cell');
assert.deepEqual(undo(), [note(14)], 'Typing a grade counts as a single operation');
assert.deepEqual(redo(), [note(18)]);
history.endEdit();
history.record([edit(18, 20)], 'cell');
assert.deepEqual(undo(), [note(18)], 'A later visit to the same cell is a separate operation');
history.record([edit(18, 18)]);
assert.deepEqual(redo(), [note(20)], 'A no-op preserves redo');
undo();
history.record([edit(18, 16)], 'cell');
assert.deepEqual(redo(), [], 'A new edit discards the redo branch');

history.clear();
history.record([edit(14, 18)], 'cell');
history.record([edit(18, 14)], 'cell');
assert.deepEqual(undo(), [], 'Typing back to the original value creates no operation');
history.record([edit(14, 15)], 'cell');
assert.deepEqual(undo(), [note(14)], 'Typing after cancelling an edit keeps the original value');

history.clear();
history.record([edit(14, 18), { before: efsrt(null), after: efsrt(20) }]);
assert.deepEqual(undo(), [note(14), efsrt(null)], 'An entire mixed paste is undone atomically');
assert.deepEqual(redo(), [note(18), efsrt(20)]);
history.record([edit(18, null), { before: efsrt(20), after: efsrt(null) }]);
assert.deepEqual(undo(), [note(18), efsrt(20)], 'An entire range deletion is restored');
assert.deepEqual(redo(), [note(null), efsrt(null)]);

history.clear();
for (let index = 0; index < 25; index++) history.record([edit(index % 21, (index + 1) % 21)]);
for (let index = 24; index >= 5; index--) assert.deepEqual(undo(), [note(index % 21)]);
assert.deepEqual(undo(), [], 'Only the last 20 operations are retained');
for (let index = 5; index < 25; index++) assert.deepEqual(redo(), [note((index + 1) % 21)]);
assert.deepEqual(redo(), []);
undo();
history.clear();
assert.deepEqual(undo(), []);
assert.deepEqual(redo(), [], 'Resetting the register clears both directions');
history.record([edit(14, 1)], 'cell', { page: 0, cell: 'first' });
history.record([edit(1, 18)], 'cell', { page: 0, cell: 'first' });
history.endEdit();
history.record([edit(18, 20)], 'other', { page: 2, cell: 'last' });
assert.deepEqual(history.undo(), { changes: [note(18)], location: { page: 2, cell: 'last' } });
assert.deepEqual(history.undo(), { changes: [note(14)], location: { page: 0, cell: 'first' } }, 'Grouped typing retains its original location');
assert.deepEqual(history.redo(), { changes: [note(18)], location: { page: 0, cell: 'first' } });
assert.deepEqual(history.redo(), { changes: [note(20)], location: { page: 2, cell: 'last' } }, 'Redo retains the page and cell');
console.log('Historial: 20 operaciones, escritura agrupada, pegado y borrado atomicos, ubicacion, bifurcacion y reinicio. Correcto.');
