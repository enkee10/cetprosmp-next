const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const mod = { exports: {} }, timers = new Map(); let clock = 0;
new Function('exports', 'setTimeout', 'clearTimeout', ts.transpileModule(fs.readFileSync('src/lib/registroGradeQueue.ts', 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS },
}).outputText)(mod.exports, fn => { timers.set(++clock, fn); return clock; }, id => timers.delete(id));
const { RegistroGradeQueue } = mod.exports;
const values = new Map();
const storage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
const note = (id, value) => ({ kind: 'nota', matriculaId: 1, indicadorCapacidadId: id, value });
(async () => {
  let finish; const sent = [];
  const queue = new RegistroGradeQueue('teacher:A', storage, changes => { sent.push(changes); return new Promise(resolve => { finish = resolve; }); }, () => true);
  queue.enqueue([note(10, 12)]);
  const first = queue.flush();
  queue.enqueue([note(10, 18), note(11, 20)]);
  assert.equal(queue.status().pending, 2, 'Typing continues while a write is pending');
  finish(); await first;
  assert.equal(queue.status().pending, 2, 'An old acknowledgement cannot erase a newer grade');
  assert.equal(queue.values()[0].value, 18);
  const restored = new RegistroGradeQueue('teacher:A', storage, async () => {}, () => true);
  assert.equal(restored.values().length, 2, 'Pending grades survive reconstruction after reload');
  const second = queue.flush(); finish(); await second;
  assert.equal(sent[1][0].value, 18);
  assert.equal(queue.status().pending, 0);
  assert.equal(values.has('teacher:A'), false, 'Acknowledged grades leave the persistent queue');
  assert.equal(new RegistroGradeQueue('teacher:B', storage, async () => {}, () => true).values().length, 0, 'Queues are isolated by identity/register');
  let online = false, calls = 0;
  const offline = new RegistroGradeQueue('offline', storage, async () => { calls++; if (calls === 1) throw Error('Network unavailable'); }, () => online);
  offline.enqueue([note(20, null)]); await offline.flush();
  assert.equal(calls, 0);
  assert.equal(offline.values()[0].value, null, 'Clearing a grade remains queued offline');
  online = true; await offline.flush();
  assert.equal(offline.status().pending, 1);
  assert(timers.size > 0, 'A transient failure schedules a retry');
  await offline.flush(); assert.equal(offline.status().pending, 0);
  const batches = [];
  const large = new RegistroGradeQueue('large', storage, async changes => { batches.push(changes); }, () => true);
  large.enqueue(Array.from({ length: 245 }, (_, i) => note(i + 1, i % 21)));
  await large.flush(); await large.flush(); await large.flush();
  assert.deepEqual(batches.map(batch => batch.length), [100, 100, 45]);
  assert.equal(large.status().pending, 0);
  const badStorage = { ...storage, setItem: () => { throw Error('Storage full'); } };
  const noStorage = new RegistroGradeQueue('quota', badStorage, async () => {}, () => true);
  noStorage.enqueue([note(30, 0)]); assert.equal(noStorage.status().backedUp, false);
  await noStorage.flush(); assert.equal(noStorage.status().pending, 0, 'Storage failure cannot block an online save');
  console.log('Cola: edición sin bloqueo, confirmaciones antiguas, recuperación, desconexión, reintentos, borrados, lotes y almacenamiento lleno. Correcto.');
})().catch(error => { console.error(error); process.exitCode = 1; });
